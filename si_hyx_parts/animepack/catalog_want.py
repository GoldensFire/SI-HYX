"""Сколько карточек каталога набирать под пак. Namespace: animepack.

Раньше выборка считалась одним множителем на весь пак: вопросов × 20, если в
паке есть песни, и × 8, если нет. Пока пак состоял из песен, кадров и
персонажей, это работало — почти каждый годный тайтл становился вопросом.

С редкими родами вопросов множитель перестал сходиться. Тайтла может не
оказаться на Sakugabooru вовсе, у арта своя (обычно узкая) рамка сложности, а
загадку по названию Gemini отвергает чаще, чем принимает: в логе пользователя
антонимы дали 5 вопросов на 81 проверенное название. Такие кандидаты сгорают
десятками на вопрос, и каталог в 2 880 карточек кончался раньше, чем пак
(«набрано 134 вопросов из 144»).

Поэтому выборка считается ПО РОДАМ ВОПРОСОВ: каждому своя цена в карточках
каталога. У песен и кадров она осталась прежней, так что обычные паки набирают
ровно столько же, сколько набирали, а редкие роды вопросов просят себе
столько, сколько им и правда нужно.
"""
from __future__ import annotations
import animepack as _api

# Во сколько карточек каталога обходится ОДИН вопрос такого рода. Числа — не
# теория, а отдача по логам: сколько тайтлов приходится перебрать, чтобы один
# стал вопросом.
#
# Дешёвые (кадр есть почти у всякого тайтла, а анаграмме не нужно даже медиа) —
# по CHEAP_COST. Песенные — по SONG_COST: песня в каталоге Shikimori есть
# примерно у четырёх тайтлов из десяти.
CHEAP_COST = 8
SONG_COST = 20
KIND_COST = {
    # Вырезки лежат хорошо если у каждого десятого тайтла каталога.
    _api.SAKUGA_KIND: 80,
    # У артов рамка сложности своя и обычно куда уже общей.
    _api.AI_ART_KIND: 50,
    _api.PIXIV_ART_KIND: 50,
    # Вики с пересказом серий есть далеко не у всякого тайтла.
    _api.PLOT_KIND: 50,
    # Нужны точное сопоставление AniList, одиночный файл серии и живой диалог.
    _api.DIALOGUE_KIND: 70,
    # Студия в карточке есть почти у всех, а вот КАДРОВ нужно сразу несколько:
    # тайтлы с парой скриншотов отсеиваются целиком.
    _api.STUDIO_KIND: 12,
}
# Загадки по названию: название должно быть русским по словам, а не только по
# буквам, — и Gemini отвергает большинство.
TITLE_COST = 60
# Антонимы дороже прочих загадок вдвойне: сверх общей проверки название должно
# ещё и переворачиваться, а берутся под них только ТВ-сериалы и полнометражки
# (см. ANTONYM_KINDS). В логе пользователя доля антонимов недобиралась именно
# поэтому — кандидаты кончались раньше пака.
ANTONYM_COST = 100


def kind_cost(kind) -> int:
    """Во сколько карточек каталога обходится вопрос этого рода."""
    if kind in _api.SONG_KINDS or kind == _api.VIDEO_KIND:
        return SONG_COST
    if kind == "antonyms":
        return ANTONYM_COST
    if kind in _api.TITLE_KINDS:
        return TITLE_COST
    return KIND_COST.get(kind, CHEAP_COST)


def anime_catalog_want(settings) -> int:
    """Сколько карточек АНИМЕ набирать в каталог под этот пак.

    Манга сюда не входит вовсе: её карточки приезжают из своего каталога со
    своим запасом, и тайтл аниме мангой стать не может."""
    quotas = settings.question_quotas
    want = sum(max(0, int(count)) * kind_cost(kind)
               for kind, count in quotas.items()
               if kind != _api.MANGA_KIND)
    return int(want)


kind_cost.__module__ = _api.__name__
anime_catalog_want.__module__ = _api.__name__
_api.kind_cost = kind_cost
_api.anime_catalog_want = anime_catalog_want
