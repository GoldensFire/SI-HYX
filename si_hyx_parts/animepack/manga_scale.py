"""Книжная шкала узнаваемости. Public namespace: animepack.

Индекс у книги считается из тех же полей, что у аниме (кто читает, кто
прочитал, кто бросил), но читателей на порядок меньше зрителей. Раньше это
чинилось одним делением: книжные пороги = анимешные ÷ 12. Деление растягивало
книжный каталог на всю лесенку 1…15 — то есть прямо утверждало, что САМУЮ
читаемую мангу узнают ровно так же, как самое смотримое аниме. На живой базе из
этого выходила чепуха: «Прощай, Эри» (131 тыс. в книжных списках, аниме нет)
получала первый уровень — легче, чем «Восхождение героя щита», которое узнают
по сериалу с 660 тыс. зрителей.

Поэтому шкала устроена иначе:

* книжный индекс переводится на ОБЩУЮ, анимешную шкалу по соответствующим
  ступеням и упирается в потолок MANGA_TOP_INDEX;
* потолок — это порог уровня MANGA_MIN_LEVEL, поэтому книга, которую не
  экранизировали, легче шестого уровня не бывает НИКОГДА. Первые пять
  уровня — «узнают все» — остаются за тем, что показывали по телевизору;
* у книги С экранизацией (или просто с аниме в той же франшизе) рядом стоит
  анимешный индекс, и уровень берётся ЛЕГЧЕ из двух: такую книгу узнают по
  сериалу, а не по тому, кто её читал.

MANGA_INDEX_LEVELS — самостоятельные пороги в книжных единицах: их показывает
панель «Что в базе» и по ним же считает index_level(manga=True).
"""
from __future__ import annotations
import animepack as _api

# Ниже какого уровня книге без аниме не подняться.
MANGA_MIN_LEVEL = 6
# Потолок книжной узнаваемости на анимешной шкале — порог MANGA_MIN_LEVEL.
MANGA_TOP_INDEX = _api.INDEX_LEVELS[MANGA_MIN_LEVEL - 1]
# Книжные пороги уровней 6…14 — анимешные пороги тех же уровней, умноженные
# на 28 000 / 15 000: шаг лесенки у книг тот же, что у аниме (×2…×2,3 на
# уровень). Прежние пороги (28 000 … 1 500, шаг ×1,44) остались от узкой
# анимешной лесенки: хвост аниме с тех пор растянули до индекса 30, а книжный
# — нет, и в 15-й уровень падало 94 % каталога манги против 11 % у аниме
# (жалоба пользователя «у манги индекс распределён не как у аниме»). Теперь
# уровни 10…14 заняты у книг так же, как у аниме; в 15-м остаётся настоящий
# хвост — книги, которые читали единицы. Верх (28 000 — шестой уровень) и
# потолок MANGA_MIN_LEVEL не менялись.
MANGA_INDEX_LEVELS = (28_000, 13_000, 5_600, 2_800, 1_300, 560, 280, 130, 56)


def manga_reach(index) -> float:
    """Книжный индекс, приведённый к общей (анимешной) шкале.

    Одно число на всё: по нему считается уровень сложности, а уровень уже
    задаёт фиксированную базовую цену. Поэтому книга и кадр больше не меряются
    двумя несводимыми линейками. Потолок здесь не «сглаживание», а само правило:
    книгу, которую не экранизировали, знают только читавшие."""
    try:
        value = float(index)
    except (TypeError, ValueError):
        return 0.0
    if value <= 0:
        return 0.0
    if value >= MANGA_INDEX_LEVELS[0]:
        return float(MANGA_TOP_INDEX)
    anime = _api.INDEX_LEVELS[MANGA_MIN_LEVEL - 1:]
    for pos in range(len(MANGA_INDEX_LEVELS) - 1):
        high_book, low_book = (MANGA_INDEX_LEVELS[pos],
                               MANGA_INDEX_LEVELS[pos + 1])
        if value < low_book:
            continue
        high_anime, low_anime = anime[pos], anime[pos + 1]
        share = (value - low_book) / float(high_book - low_book)
        return low_anime + share * (high_anime - low_anime)
    # Ниже последнего книжного порога обе шкалы сходятся в нуле. Точное
    # линейное продолжение сохраняет границу 14/15 и порядок цен внутри хвоста.
    return value * float(anime[-1]) / MANGA_INDEX_LEVELS[-1]

manga_reach.__module__ = _api.__name__
_api.manga_reach = manga_reach
_api.MANGA_MIN_LEVEL = MANGA_MIN_LEVEL
_api.MANGA_TOP_INDEX = MANGA_TOP_INDEX
_api.MANGA_INDEX_LEVELS = MANGA_INDEX_LEVELS
