def _plural(number: int, forms) -> str:
    """«1 карточка», «2 карточки», «5 карточек» — иначе счётчик читается как
    машинный вывод, а не как строка про базу."""
    number = abs(int(number))
    if number % 10 == 1 and number % 100 != 11:
        return forms[0]
    if 2 <= number % 10 <= 4 and not 12 <= number % 100 <= 14:
        return forms[1]
    return forms[2]


def _fmt_count(number) -> str:
    return f"{int(number):,}".replace(",", " ")


def _fmt_when(stamp: float) -> str:
    if not stamp:
        return ""
    return time.strftime("обновлено %d.%m.%Y", time.localtime(float(stamp)))


class PartBlock(QFrame):
    """Одна часть базы: счётчик, когда трогали и своя кнопка обновления."""

    def __init__(self, part: str, title: str, unit: str, action: str,
                 on_action, parent=None):
        super().__init__(parent)
        self.part = part
        self._unit = unit
        self._action = action
        self.setFrameShape(QFrame.Shape.StyledPanel)
        self.setStyleSheet(
            f"PartBlock {{ background: {api.C['surface2']}; "
            f"border: 1px solid {api.C['border']}; border-radius: 6px; }}")
        layout = QVBoxLayout(self)
        layout.setContentsMargins(10, 8, 10, 8)
        layout.setSpacing(4)
        # Фон подписи обязан быть прозрачным: в общей теме есть правило
        # «QWidget { background-color: … }», и оно достаёт QLabel тоже — стоит
        # задать подписи СВОЙ стиль, как она начинает закрашивать свой
        # прямоугольник цветом окна. Получались тёмные полосы поперёк блока
        # (просьба пользователя убрать).
        flat = "background: transparent; border: none;"
        self.title = QLabel(title)
        self.title.setStyleSheet(
            f"color: {api.C['text']}; font-weight: 600; {flat}")
        self.count = QLabel("—")
        self.count.setStyleSheet(
            f"color: {api.C['accent']}; font-size: 15px; {flat}")
        self.when = QLabel("")
        self.when.setStyleSheet(
            f"color: {api.C['text3']}; font-size: 11px; {flat}")
        if part == "manga":
            self.button = refresh_button(on_action, self)
        else:
            self.button = QPushButton(action)
            self.button.clicked.connect(lambda: on_action(self.part))
        for widget in (self.title, self.count, self.when):
            layout.addWidget(widget)
        layout.addWidget(self.button)
        # Подсказку вешаем и на сами подписи: событие ToolTip приходит виджету
        # под курсором, а курсор чаще всего стоит именно на строчке со счётом.
        # Сам попап — фирменный тёмный (HoverTipManager), не синий системный.
        tip = TIPS.get(part, "")
        for widget in (self, self.title, self.count, self.when):
            widget.setToolTip(tip)

    def set_state(self, count: int, fetched: float, running: bool,
                  busy: bool) -> None:
        """running — обновляется именно эта часть; busy — занята база вообще."""
        self.count.setText(f"{_fmt_count(count)} "
                           f"{_plural(count, self._unit)}")
        self.when.setText("идёт сбор…" if running else _fmt_when(fetched))
        self.button.setEnabled(running or not busy)
        self.button.setText("Остановить" if running else self._action)
        if self.part == "manga":
            sync_menu(self.button, busy)


def build_blocks(on_action, parent=None) -> dict:
    """{ключ части: блок} в порядке PARTS."""
    return {part: PartBlock(part, title, unit, action, on_action, parent)
            for part, title, unit, action in PARTS}
