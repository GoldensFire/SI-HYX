def clean_terms(values) -> list[str]:
    """Приводит правки пользователя к виду списка меток без повторов."""
    out, seen = [], set()
    for value in (values or []):
        term = " ".join(str(value or "").split()).strip()
        if not term or term.casefold() in seen:
            continue
        seen.add(term.casefold())
        out.append(term)
    return out
